// Builds the prebuilt dictionary database shipped in the app bundle.
//
//   assets/datasets/dictionaries.json  (source of truth, edit this)
//     -> assets/db/dictionary.db
//     -> lib/databases/dictionaries/dictionary_db_version.dart
//
// Run from VS Code (Terminal > Run Task > "Generate dictionary.db") or:
//   cd tool/dictionary_db && dart pub get && dart run bin/build_dictionary_db.dart
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:sqlite3/sqlite3.dart';

// Bump when the table layout below changes, so installs re-copy the database
// even if the JSON is unchanged.
const schemaRevision = 1;

const columns = [
  'alphabet',
  'title',
  'full_title',
  'category',
  'description',
  'created_at',
  'updated_at',
];

void main() {
  final root = File.fromUri(Platform.script).parent.parent.parent.parent;
  final jsonFile = File('${root.path}/assets/datasets/dictionaries.json');
  final dbFile = File('${root.path}/assets/db/dictionary.db');
  final versionFile = File(
      '${root.path}/lib/databases/dictionaries/dictionary_db_version.dart');

  final jsonBytes = jsonFile.readAsBytesSync();
  final rows = (jsonDecode(utf8.decode(jsonBytes))['data'] as List)
      .cast<Map<String, dynamic>>();

  // The version is derived from the data, so it changes whenever the JSON
  // does. It must fit SQLite's signed 32-bit user_version.
  final digest = sha256.convert([...jsonBytes, schemaRevision]).bytes;
  final version =
      ((digest[0] << 24) | (digest[1] << 16) | (digest[2] << 8) | digest[3]) &
          0x7fffffff;

  dbFile.parent.createSync(recursive: true);
  if (dbFile.existsSync()) dbFile.deleteSync();

  final db = sqlite3.open(dbFile.path);
  try {
    db.execute('''
      CREATE TABLE dictionaries (
        id INTEGER PRIMARY KEY,
        alphabet TEXT NULL,
        title TEXT NULL,
        full_title TEXT NULL,
        category TEXT NULL,
        description TEXT NULL,
        created_at TEXT NULL,
        updated_at TEXT NULL
      )
    ''');

    // ids follow the JSON order (1..n), exactly as the old runtime seeding
    // assigned them. Bookmarks and histories store these ids, so never
    // reorder or remove entries in the JSON, only append new ones.
    final insert = db.prepare(
        'INSERT INTO dictionaries (id, ${columns.join(', ')}) '
        'VALUES (?, ${List.filled(columns.length, '?').join(', ')})');
    db.execute('BEGIN');
    for (var i = 0; i < rows.length; i++) {
      insert.execute([i + 1, for (final c in columns) rows[i][c]]);
    }
    db.execute('COMMIT');
    insert.close();

    db.execute('CREATE INDEX idx_dictionaries_alphabet ON dictionaries (alphabet)');
    db.execute('CREATE INDEX idx_dictionaries_category ON dictionaries (category)');
    db.execute('PRAGMA user_version = $version');
    db.execute('VACUUM');
  } finally {
    db.close();
  }

  versionFile.writeAsStringSync('''
// GENERATED by tool/dictionary_db/bin/build_dictionary_db.dart. Do not edit.

/// `PRAGMA user_version` of assets/db/dictionary.db.
const int dictionaryDbVersion = $version;

/// Number of entries in assets/db/dictionary.db.
const int dictionaryDbEntries = ${rows.length};
''');

  stdout.writeln('Wrote ${rows.length} entries to assets/db/dictionary.db '
      '(${dbFile.lengthSync()} bytes, version $version)');
}
